export default function PixelSprite({ item }: { item: Item }) {
  const type = /晶|种/.test(item.name)
    ? "crystal"
    : /粉|渣|泥|砂|碳/.test(item.name)
      ? "dust"
      : /芯片|板|模块|门控|片/.test(item.name)
        ? "chip"
        : /记录|册|卡|报告|回执|模板/.test(item.name)
          ? "book"
          : /工具|探针|扳手|量具|头/.test(item.name)
            ? "tool"
            : /设备|工位/.test(item.kind) || /塔|机|台|炉|框/.test(item.name)
              ? "machine"
              : "plate";
  const index = [...item.id].reduce((sum, c) => sum + c.charCodeAt(0), 0) % 5;
  const palettes = [
    ["#e4efd2", "#abc98b", "#6f9758", "#466b42", "#2b4732"],
    ["#e7efdd", "#a7c9bd", "#66998f", "#437772", "#285354"],
    ["#ffedc7", "#dabc84", "#b08a50", "#7a623c", "#4f4a34"],
    ["#e2e9ef", "#a5bacb", "#7492b0", "#4c6482", "#34485f"],
    ["#f0e0d1", "#d4ae8d", "#b88665", "#875d4f", "#5c463f"],
  ];
  const colors = palettes[index];
  return (
    <svg
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role="img"
      aria-label={`${item.name}，临时像素贴图`}
    >
      <title>{item.name} · 示例贴图</title>
      {patterns[type].flatMap((row, y) =>
        [...row].map((p, x) =>
          p === "." ? null : (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y + 1}
              width="1"
              height="1"
              fill={colors[Number(p) - 1]}
            />
          ),
        ),
      )}
    </svg>
  );
}
